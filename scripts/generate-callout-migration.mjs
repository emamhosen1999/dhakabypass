// One-off generator for db/sql/22-callout-migration.sql.
//
// Reads every rich-text block whose body carries an inline provenance marker —
// `<p class="db-pending">` or `<div class="db-archive">` — and emits guarded
// SQL that turns the marker into a `callout` block (tone pending / legacy),
// keeping the prose before it in the rich-text block. Run against a FRESH
// import of 01..21 (DB_NAME=dhakabypass_fresh), never the development
// database: that one is already migrated, and its ids differ anyway. Commit
// the SQL; the SQL is the artifact, this is how it was made.
//
//   DB_NAME=dhakabypass_fresh node scripts/generate-callout-migration.mjs > db/sql/22-callout-migration.sql
import mysql from 'mysql2/promise';

const FIRST_NEW_ID = 360; // above every seeded block id (359 = grievance form)

const c = await mysql.createConnection({ host: '127.0.0.1', user: 'root', database: process.env.DB_NAME || 'dhakabypass', charset: 'utf8mb4' });
const [rows] = await c.query(`SELECT bt.block_id, bt.locale, b.page_id, b.sort_order, p.slug, bt.data, bt.status
  FROM block_translations bt JOIN blocks b ON b.id = bt.block_id JOIN pages p ON p.id = b.page_id
  WHERE b.type = 'rich-text' ORDER BY b.page_id, b.sort_order, bt.block_id, bt.locale`);
await c.end();

const MARK = /(<p class="db-pending">[\s\S]*?<\/p>|<div class="db-archive">[\s\S]*?<\/div>)/;
const PENDING = /^<p class="db-pending"><span class="db-pending-tag">[^<]*<\/span>([\s\S]*)<\/p>$/;
const LEGACY = /^<div class="db-archive"><p class="db-archive-notice"><strong class="db-archive-tag">[^<]*<\/strong>([\s\S]*?)<\/p>([\s\S]*)<\/div>$/;

/** [{kind, html}] — prose and marker segments in order. */
function segments(body) {
  return String(body || '').split(MARK).map((s) => s.trim()).filter(Boolean).map((s) => {
    const m = s.match(MARK);
    if (m && m[0] === s) return { kind: s.startsWith('<p') ? 'pending' : 'legacy', html: s };
    return { kind: 'prose', html: s };
  });
}

/** The callout's data for one marker. The standard tag is dropped: the
 *  callout renders it from ui_strings, once, for every notice. */
function calloutData(seg) {
  if (seg.kind === 'pending') {
    const m = seg.html.match(PENDING);
    if (!m) throw new Error(`unexpected pending shape: ${seg.html.slice(0, 120)}`);
    return { tone: 'pending', heading: '', body: `<p>${m[1].trim()}</p>` };
  }
  const m = seg.html.match(LEGACY);
  if (!m) throw new Error(`unexpected legacy shape: ${seg.html.slice(0, 120)}`);
  return { tone: 'legacy', heading: '', body: `<p>${m[1].trim()}</p>${m[2].trim()}` };
}

const q = (s) => `'${String(s).replace(/\\/g, '\\\\').replace(/'/g, "''")}'`;
const json = (o) => q(JSON.stringify(o));

const byBlock = new Map();
for (const r of rows) {
  const d = typeof r.data === 'string' ? JSON.parse(r.data) : r.data;
  const segs = segments(d.body);
  if (!segs.some((s) => s.kind !== 'prose')) continue;
  const e = byBlock.get(r.block_id) || { page: r.slug, pageId: r.page_id, sort: r.sort_order, locales: {} };
  e.locales[r.locale] = { segs, data: d, status: r.status };
  byBlock.set(r.block_id, e);
}

const out = [];
out.push(`-- 22-callout-migration.sql — inline provenance markers become callout blocks.
--
-- GENERATED by scripts/generate-callout-migration.mjs from the seeded content;
-- do not edit by hand, regenerate.
--
-- The "Not yet published" and "Previous website information" notices were
-- <p class="db-pending"> and <div class="db-archive"> paragraphs typed inside
-- rich-text bodies: a convention held together by a class name that one
-- careless edit in the rich-text editor drops, silently turning a legal
-- provenance marker into an ordinary paragraph. The callout block makes the
-- tone a FIELD (lib/blocks/types/callout.js); its standard tag comes from
-- ui_strings so every notice reads the same and is edited in one place.
--
-- Two shapes were found, both identical across en/bn/zh:
--   [marker]          the block IS the notice -> its type becomes callout
--   [prose, marker]   the marker is trimmed off the body and a new callout
--                     block is inserted at the same sort_order with a higher
--                     id, so it renders directly after (order is sort_order, id)
--
-- Blocks are located by PAGE SLUG + TYPE + a run of the English marker text,
-- never by id or sort order: 02-seed.sql numbers these blocks 12, 16, 18...
-- and a re-seeded development database numbers the same blocks 135, 137,
-- 143...; 07-block-order.sql renumbers sort orders and an operator can drag a
-- block. The content is the one thing both databases share.
--
-- Every statement is guarded on the marker still being present, so a
-- re-import changes nothing and an operator's later edit is never overwritten.
-- ID map: new blocks ${FIRST_NEW_ID}+.
`);

/**
 * The SQL locating one seeded rich-text block: page slug, type, and a
 * distinctive run of the ENGLISH marker text found with INSTR (no LIKE
 * wildcards to escape). Not sort_order: 07-block-order.sql renumbers blocks
 * densely, an operator may have dragged one, and a locator keyed on a number
 * that moves would convert the wrong paragraph.
 */
const snippetOf = (seg) => {
  const inner = seg.html.replace(/<[^>]+>/g, ' ').replace(/\s+/g, ' ').trim();
  // The END of the marker, not the start: every legacy notice opens with the
  // same standard sentence, and a page can carry two of them.
  return inner.slice(-80);
};
const locate = (e, seg) => `(SELECT b.\`id\` FROM \`blocks\` b JOIN \`pages\` p ON p.\`id\` = b.\`page_id\`
    JOIN \`block_translations\` t ON t.\`block_id\` = b.\`id\` AND t.\`locale\` = 'en'
    WHERE p.\`slug\` = ${q(e.page)} AND b.\`type\` = 'rich-text'
      AND INSTR(JSON_UNQUOTE(JSON_EXTRACT(t.\`data\`, '$.body')), ${q(snippetOf(seg))}) > 0
    ORDER BY b.\`id\` LIMIT 1)`;
const pageOf = (e) => `(SELECT \`id\` FROM \`pages\` WHERE \`slug\` = ${q(e.page)} LIMIT 1)`;

let nextId = FIRST_NEW_ID;
for (const [id, e] of byBlock) {
  const shapes = Object.values(e.locales).map((l) => l.segs.map((s) => s.kind).join(','));
  if (!shapes.every((s) => s === shapes[0])) throw new Error(`block ${id} differs across locales: ${shapes}`);
  const shape = shapes[0];
  out.push(`\n-- /${e.page} sort ${e.sort} (source block ${id}): ${shape}`);

  if (shape === 'pending' || shape === 'legacy') {
    const marker = shape === 'pending' ? 'db-pending' : 'db-archive';
    // Translations first, then the type: once the type is callout the
    // locator above no longer finds the block, which is what makes a second
    // import a no-op.
    out.push(`SET @blk = ${locate(e, e.locales.en.segs[0])};`);
    for (const [locale, l] of Object.entries(e.locales)) {
      const data = calloutData(l.segs[0]);
      out.push(`UPDATE \`block_translations\` SET \`data\` = ${json(data)} WHERE \`block_id\` = @blk AND \`locale\` = ${q(locale)}
  AND JSON_UNQUOTE(JSON_EXTRACT(\`data\`, '$.body')) LIKE '%${marker}%';`);
    }
    // The type flips only once every translation carries a tone — i.e. the
    // updates above ran — and never for a rich-text block that merely has no
    // marker, which is what a re-run after reordering would otherwise find.
    out.push(`UPDATE \`blocks\` SET \`type\` = 'callout' WHERE \`id\` = @blk AND \`type\` = 'rich-text'
  AND NOT EXISTS (SELECT 1 FROM \`block_translations\` WHERE \`block_id\` = @blk AND JSON_EXTRACT(\`data\`, '$.tone') IS NULL);`);
    continue;
  }

  if (shape === 'prose,pending' || shape === 'prose,legacy') {
    const kind = shape.split(',')[1];
    const newId = nextId++;
    const marker = kind === 'pending' ? 'db-pending' : 'db-archive';
    out.push(`SET @blk = ${locate(e, e.locales.en.segs[1])};`);
    out.push(`SET @sort = (SELECT \`sort_order\` FROM \`blocks\` WHERE \`id\` = @blk);`);
    out.push(`INSERT IGNORE INTO \`blocks\` (\`id\`, \`page_id\`, \`type\`, \`sort_order\`, \`settings\`, \`status\`)
  SELECT ${newId}, ${pageOf(e)}, 'callout', @sort, NULL, 'published' FROM DUAL
  WHERE @blk IS NOT NULL AND EXISTS (SELECT 1 FROM \`block_translations\` WHERE \`block_id\` = @blk AND \`locale\` = 'en' AND JSON_UNQUOTE(JSON_EXTRACT(\`data\`, '$.body')) LIKE '%${marker}%');`);
    for (const [locale, l] of Object.entries(e.locales)) {
      const prose = { ...l.data, body: l.segs[0].html };
      const data = calloutData(l.segs[1]);
      out.push(`INSERT IGNORE INTO \`block_translations\` (\`block_id\`, \`locale\`, \`data\`, \`status\`)
  SELECT ${newId}, ${q(locale)}, ${json(data)}, ${q(l.status)} FROM DUAL
  WHERE EXISTS (SELECT 1 FROM \`block_translations\` WHERE \`block_id\` = @blk AND \`locale\` = ${q(locale)} AND JSON_UNQUOTE(JSON_EXTRACT(\`data\`, '$.body')) LIKE '%${marker}%');`);
      out.push(`UPDATE \`block_translations\` SET \`data\` = ${json(prose)} WHERE \`block_id\` = @blk AND \`locale\` = ${q(locale)}
  AND JSON_UNQUOTE(JSON_EXTRACT(\`data\`, '$.body')) LIKE '%${marker}%';`);
    }
    continue;
  }
  throw new Error(`block ${id}: unhandled shape ${shape}`);
}
process.stdout.write(`${out.join('\n')}\n`);
